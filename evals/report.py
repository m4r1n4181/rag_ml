"""
Write data/eval/results.md from the JSON results of the other eval steps.

    python -m evals.report
"""
from evals.common import EVAL_DIR, RESULTS_DIR, load_json

OUT = EVAL_DIR / "results.md"


def retrieval_table(report: dict, k: int) -> list[str]:
    lines = [
        f"| Configuration | Recall@{k} | Precision@{k} | MRR | nDCG@{k} | unjudged | ms/query |",
        "|---|---|---|---|---|---|---|",
    ]
    for name, r in report["systems"].items():
        m = r.get(f"@{k}")
        if m:
            lines.append(
                f"| {r['description']} | {m['recall']:.3f} | {m['precision']:.3f} | {m['mrr']:.3f} | "
                f"{m['ndcg']:.3f} | {m['unjudged']:.0%} | {r['ms_per_query']:.0f} |"
            )
    return lines


def answers_table(report: dict) -> list[str]:
    lines = [
        "| Pipeline | Retrieval | k | Completeness | Faithfulness | Answers with ≥1 unsupported statement |",
        "|---|---|---|---|---|---|",
    ]
    for name, r in report["pipelines"].items():
        lines.append(
            f"| {name} | {r['system']} | {r['k']} | {r['completeness']:.3f} | {r['faithfulness']:.3f} | "
            f"{r['answers_with_unsupported_claims']:.0%} |"
        )
    return lines


def main():
    out = ["# Evaluation results", "", "Generated by `python -m evals.report`. Method: see the Evaluation section of the README.", ""]

    for subset, title in (("test", "Retrieval, test set"), ("dev", "Retrieval, dev set (used for decisions)")):
        report = load_json(RESULTS_DIR / f"retrieval_{subset}.json")
        if report:
            out += [f"## {title} ({report['n_questions']} questions)", ""]
            for k in (5, 10):
                out += retrieval_table(report, k) + [""]

    for subset, title in (("test", "Answers, test set: before vs after"), ("dev", "Answers, dev set: choosing k")):
        report = load_json(RESULTS_DIR / f"answers_{subset}.json")
        out += [f"## {title}", ""]
        if report:
            out += [f"{report['pipelines'][next(iter(report['pipelines']))]['n']} questions. "
                    f"Answers by `{report['answer_model']}`, judged by `{report['judge_model']}`.", ""]
            out += answers_table(report) + [""]
        else:
            out += [f"Not run yet: `python -m evals.answers --subset {subset}`", ""]

    support = load_json(EVAL_DIR / "key_point_support.json")
    if support:
        labels = support["labels"]
        n = sum(len(v) for v in labels.values())
        ok = sum(sum(v) for v in labels.values())
        out += ["## Are the reference answers grounded in the course materials?", "",
                f"Checked by hand on {len(labels)} test questions: {ok} of {n} key points "
                f"({ok / n:.0%}) are stated in the slides or textbook.", ""]

    agreement = load_json(RESULTS_DIR / "judge_agreement.json")
    out += ["## Judge vs human", ""]
    if agreement:
        out += [f"{agreement['answers']} answers, {agreement['key_points']} key points: "
                f"agreement {agreement['agreement']:.0%}, Cohen's kappa {agreement['kappa']:.2f}.", ""]
    else:
        out += ["Not run yet: `python -m evals.human_check --n 15`", ""]

    OUT.write_text("\n".join(out), encoding="utf-8")
    print(f"Wrote {OUT}")


if __name__ == "__main__":
    main()
